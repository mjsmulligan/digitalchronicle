"""Build the offline station lookup from Trainline's ODbL-licensed stations.csv.

Each output entry is [name, lat, lon, timezone, city] where city is the human-readable
city name derived via the parent_station_id \u2192 is_city join (empty string when unknown).

Outputs raw JSON when the destination ends in .json, TypeScript otherwise.
"""

import csv
import json
import sys
import unicodedata
from collections import defaultdict
from pathlib import Path


def key(name: str) -> str:
    return (
        "".join(
            char
            for char in unicodedata.normalize("NFD", name)
            if not ("\u0300" <= char <= "\u036f")
        )
        .replace(".", "")
        .strip()
        .upper()
    )


def main(source: Path, destination: Path) -> None:
    # \u2500\u2500 Pass 1: build id \u2192 city-name map from is_city=t rows \u2500\u2500\u2500\u2500\u2500\u2500\u2500\u2500\u2500\u2500\u2500\u2500\u2500\u2500\u2500\u2500
    city_by_id: dict[str, str] = {}
    with source.open(encoding="utf-8-sig", newline="") as file:
        for row in csv.DictReader(file, delimiter=";"):
            if row.get("is_city") == "t" and row.get("name"):
                city_by_id[row["id"]] = row["name"]

    # \u2500\u2500 Pass 2: collect suggestable stations, join city via parent_station_id \u2500
    candidates = defaultdict(list)
    with source.open(encoding="utf-8-sig", newline="") as file:
        for row in csv.DictReader(file, delimiter=";"):
            if (
                row["is_suggestable"] != "t"
                or not row["name"]
                or not row["latitude"]
                or not row["longitude"]
                or not row["time_zone"]
            ):
                continue
            try:
                lat, lon = float(row["latitude"]), float(row["longitude"])
            except ValueError:
                continue
            if not (-90 <= lat <= 90 and -180 <= lon <= 180):
                continue

            # City: own name when this row is already a city entry; otherwise
            # follow parent_station_id to an is_city row.
            if row.get("is_city") == "t":
                city = row["name"]
            else:
                city = city_by_id.get(row.get("parent_station_id", ""), "")

            candidates[key(row["name"])].append(
                (row["name"], round(lat, 5), round(lon, 5), row["time_zone"], row["country"], city)
            )

    # \u2500\u2500 Resolve ambiguity: keep only entries where all matches share the same
    #    lat/lon/timezone (same physical place, possibly different city labels) \u2500
    stations = {}
    for name, matches in candidates.items():
        if len({match[1:4] for match in matches}) == 1:
            label, lat, lon, timezone, _country, city = matches[0]
            stations[name] = [label, lat, lon, timezone, city]

    if len(stations) < 50_000:
        raise ValueError(f"Expected at least 50,000 unambiguous stations; found {len(stations)}")

    data = json.dumps(stations, ensure_ascii=False, separators=(",", ":"), sort_keys=True)

    if destination.suffix == ".json":
        destination.write_text(data, encoding="utf-8")
    else:
        destination.write_text(
            "// Generated by scripts/build-station-gazetteer.py from Trainline EU stations.csv (ODbL 1.0).\n"
            "// See README.md for source and attribution. Ambiguous names are excluded.\n"
            "export const STATIONS: Record<string, [string, number, number, string, string]> = "
            + data
            + ";\n",
            encoding="utf-8",
        )
    print(f"Wrote {len(stations)} unambiguous places to {destination}")


if __name__ == "__main__":
    if len(sys.argv) != 3:
        sys.exit(
            "Usage: python3 scripts/build-station-gazetteer.py stations.csv "
            "src/lib/journal/stations.generated.json"
        )
    main(Path(sys.argv[1]), Path(sys.argv[2]))
